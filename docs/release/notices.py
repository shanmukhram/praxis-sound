"""Writes THIRD-PARTY-NOTICES.txt: the licence texts of everything Praxis Sound ships.

Run from the repository root (needs cargo and an `npm ci` in app/):

    python -I docs/release/notices.py

Covers every crate compiled into the shipped binaries (praxis-app, praxis, praxis-mcp) for
Windows x64, normal dependencies only (build scripts and proc-macros run at build time and are
not shipped, but crates whose licence asks for notices are listed anyway when MPL-2.0), the npm
packages in the front-end bundle (dependencies, not devDependencies), and the instrument pack the
app downloads. Identical licence texts are printed once with the crates that use them.
"""
import hashlib
import json
import os
import re
import subprocess
import sys

ROOT = os.getcwd()
TARGET = 'x86_64-pc-windows-msvc'
SHIPPED = ['praxis-app', 'praxis-cli', 'praxis-mcp']
LICENSE_FILE = re.compile(r'^(LICEN[CS]E|COPYING|NOTICE|UNLICENSE|COPYRIGHT)([-._].*)?$', re.I)


def metadata():
    out = subprocess.run(
        ['cargo', 'metadata', '--format-version', '1', '--filter-platform', TARGET, '--locked'],
        cwd=ROOT, capture_output=True, text=True, encoding='utf8', check=True).stdout
    return json.loads(out)


def shipped_crates(meta):
    """Crates reachable from the shipped binaries through normal dependencies."""
    nodes = {n['id']: n for n in meta['resolve']['nodes']}
    pkgs = {p['id']: p for p in meta['packages']}
    roots = [p['id'] for p in meta['packages'] if p['name'] in SHIPPED and p['source'] is None]
    seen, stack, build_only = set(), list(roots), set()
    while stack:
        pid = stack.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for d in nodes[pid]['deps']:
            kinds = {k['kind'] for k in d['dep_kinds']}
            if None in kinds:  # a normal dependency
                stack.append(d['pkg'])
    # MPL-2.0 crates reached only at build time (tauri's code generation) still get a line.
    all_ids = set()
    stack = list(roots)
    while stack:
        pid = stack.pop()
        if pid in all_ids:
            continue
        all_ids.add(pid)
        for d in nodes[pid]['deps']:
            if any(k['kind'] != 'dev' for k in d['dep_kinds']):
                stack.append(d['pkg'])
    for pid in all_ids - seen:
        if 'MPL' in (pkgs[pid].get('license') or ''):
            build_only.add(pid)
    third = [pkgs[i] for i in seen if pkgs[i]['source'] is not None]
    return sorted(third, key=lambda p: (p['name'], p['version'])), [pkgs[i] for i in sorted(build_only)]


def licence_texts(pkg_dir):
    texts = []
    for name in sorted(os.listdir(pkg_dir)):
        path = os.path.join(pkg_dir, name)
        if os.path.isfile(path) and LICENSE_FILE.match(name):
            with open(path, encoding='utf8', errors='replace') as f:
                texts.append((name, f.read().replace('\r\n', '\n').strip()))
    return texts


def main():
    meta = metadata()
    crates, build_only = shipped_crates(meta)
    groups = {}  # text hash -> (text, [labels])
    missing = []
    for p in crates:
        label = f"{p['name']} {p['version']} ({p.get('license') or 'see text'})"
        texts = licence_texts(os.path.dirname(p['manifest_path']))
        if not texts:
            missing.append(p)
            continue
        for fname, text in texts:
            h = hashlib.sha256(text.encode()).hexdigest()
            groups.setdefault(h, [text, []])[1].append(f'{label}: {fname}')

    npm = []
    lock = json.load(open(os.path.join(ROOT, 'app', 'package-lock.json'), encoding='utf8'))
    for path, info in sorted(lock['packages'].items()):
        if not path or info.get('dev') or info.get('optional'):
            continue
        d = os.path.join(ROOT, 'app', path)
        label = f"npm {path.split('node_modules/')[-1]} {info.get('version')} ({info.get('license')})"
        texts = licence_texts(d) if os.path.isdir(d) else []
        if not texts:
            sys.exit(f'no licence text for {label}: run `npm ci` in app/ first')
        npm.append(label)
        for fname, text in texts:
            h = hashlib.sha256(text.encode()).hexdigest()
            groups.setdefault(h, [text, []])[1].append(f'{label}: {fname}')

    index = json.load(open(os.path.join(ROOT, 'packs', 'index.json'), encoding='utf8'))
    out = []
    w = out.append
    w('THIRD-PARTY NOTICES FOR PRAXIS SOUND')
    w('=' * 37)
    w('')
    w('Praxis Sound is licensed under MIT OR Apache-2.0 (see LICENSE-MIT and LICENSE-APACHE).')
    w('It includes the third-party components below, each under its own licence. This file is')
    w('generated by docs/release/notices.py from Cargo.lock and app/package-lock.json.')
    w('')
    w(f'Rust crates compiled into the app, the praxis CLI and the MCP server ({TARGET}): {len(crates)}')
    w(f'npm packages in the window\'s front end: {len(npm)}')
    w('')
    w('MPL-2.0 components (used unmodified; their source code is available at the links below):')
    mpl = [p for p in crates if 'MPL' in (p.get('license') or '')]
    for p in mpl:
        w(f"  - {p['name']} {p['version']} (through Tauri): https://crates.io/crates/{p['name']}/{p['version']}")
    for p in build_only:
        w(f"  - {p['name']} {p['version']} (build time only, through Tauri's code generation; not in the "
          f"shipped binaries): https://crates.io/crates/{p['name']}/{p['version']}")
    w('')
    w('Instrument packs (downloaded by the app on request, not part of the installer):')
    for e in index['packs']:
        w(f"  - {e['title']}, version {e['version']}: {e['license']}. {e['attribution']}. Source: {e['source_page']}")
    w('    CC0-1.0: the authors dedicated the work to the public domain; no conditions apply.')
    w('')
    w('Optional external program, never bundled: ffmpeg (LGPL/GPL), used only if installed separately.')
    w('')
    if missing:
        w('Crates whose package holds no licence file (licence as declared in their Cargo.toml; the')
        w('standard text of that licence is printed below under another crate):')
        for p in missing:
            w(f"  - {p['name']} {p['version']}: {p.get('license')}")
        w('')
    for h, (text, labels) in sorted(groups.items(), key=lambda kv: sorted(kv[1][1])[0]):
        w('-' * 78)
        for label in sorted(labels):
            w(label)
        w('')
        w(text)
        w('')
    path = os.path.join(ROOT, 'THIRD-PARTY-NOTICES.txt')
    with open(path, 'w', encoding='utf8', newline='\n') as f:
        f.write('\n'.join(out))
    print(f'{path}: {len(crates)} crates, {len(npm)} npm packages, {len(groups)} distinct texts, '
          f'{len(missing)} crates without a licence file, {len(mpl)} MPL in app, {len(build_only)} MPL build-only')


main()
