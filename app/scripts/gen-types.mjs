#!/usr/bin/env node
// Generates src/score/generated.ts from schema/score.schema.json and schema/patch.schema.json.
// No dependencies: handles exactly the JSON Schema subset schemars emits for the Score types
// ($ref, enum, const, oneOf/anyOf, nullable type arrays, objects, maps, arrays).
//
//   node scripts/gen-types.mjs           write the file
//   node scripts/gen-types.mjs --check   exit 1 if the file is stale (used by a unit test)

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '..', '..');
const out = resolve(here, '..', 'src', 'score', 'generated.ts');

export function generate() {
  const score = JSON.parse(readFileSync(resolve(repo, 'schema', 'score.schema.json'), 'utf8'));
  const patch = JSON.parse(readFileSync(resolve(repo, 'schema', 'patch.schema.json'), 'utf8'));

  const defs = new Map();
  for (const schema of [score, patch]) {
    for (const [name, def] of Object.entries(schema.$defs ?? {})) {
      const prev = defs.get(name);
      if (prev && JSON.stringify(prev) !== JSON.stringify(def)) {
        throw new Error(`definition ${name} differs between score and patch schemas`);
      }
      defs.set(name, def);
    }
  }
  defs.set(score.title, rootAsDef(score));
  defs.set(patch.title, rootAsDef(patch));

  const lines = [
    '// GENERATED by app/scripts/gen-types.mjs from schema/score.schema.json and',
    '// schema/patch.schema.json. Do not edit by hand: run `npm run gen:types`.',
    '// Fields with schema defaults are optional here; use normalizeScore() for filled values.',
    '/* eslint-disable */',
    '',
  ];
  for (const name of [...defs.keys()].sort()) {
    lines.push(emitDef(name, defs.get(name)), '');
  }
  return lines.join('\n');
}

function rootAsDef(schema) {
  const { $defs, $schema, title, ...rest } = schema;
  return rest;
}

function doc(description, indent) {
  if (!description) return '';
  const body = description.split('\n').map((l) => `${indent} * ${l}`.trimEnd());
  return `${indent}/**\n${body.join('\n')}\n${indent} */\n`;
}

function emitDef(name, def) {
  const head = doc(def.description, '');
  if (def.type === 'object' && def.properties) {
    return `${head}export interface ${name} ${objectBody(def, '')}`;
  }
  return `${head}export type ${name} = ${tsType(def, '')};`;
}

function objectBody(def, indent) {
  const req = new Set(def.required ?? []);
  const inner = indent + '  ';
  const fields = Object.keys(def.properties)
    .sort()
    .map((key) => {
      const prop = def.properties[key];
      const opt = req.has(key) ? '' : '?';
      return `${doc(prop.description, inner)}${inner}${key}${opt}: ${tsType(prop, inner)};`;
    });
  return `{\n${fields.join('\n')}\n${indent}}`;
}

function union(types) {
  const uniq = [...new Set(types)];
  return uniq.join(' | ');
}

function wrapArray(t) {
  return /[|&]/.test(t) ? `(${t})[]` : `${t}[]`;
}

function tsType(s, indent) {
  if (s.$ref) return s.$ref.replace('#/$defs/', '');
  if ('const' in s) return JSON.stringify(s.const);
  if (s.enum) return union(s.enum.map((v) => JSON.stringify(v)));
  if (s.oneOf) return union(s.oneOf.map((x) => tsType(x, indent)));
  if (s.anyOf) return union(s.anyOf.map((x) => tsType(x, indent)));
  if (Array.isArray(s.type)) {
    return union(s.type.map((t) => tsType({ ...s, type: t }, indent)));
  }
  switch (s.type) {
    case 'integer':
    case 'number':
      return 'number';
    case 'string':
      return 'string';
    case 'boolean':
      return 'boolean';
    case 'null':
      return 'null';
    case 'array':
      return wrapArray(s.items ? tsType(s.items, indent) : 'unknown');
    case 'object':
      if (s.properties) return objectBody(s, indent);
      if (s.additionalProperties && typeof s.additionalProperties === 'object') {
        return `Record<string, ${tsType(s.additionalProperties, indent)}>`;
      }
      return 'Record<string, unknown>';
    default:
      throw new Error(`unsupported schema: ${JSON.stringify(s).slice(0, 120)}`);
  }
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const text = generate();
  if (process.argv.includes('--check')) {
    const current = readFileSync(out, 'utf8').replace(/\r\n/g, '\n');
    if (current !== text) {
      console.error('src/score/generated.ts is stale: run `npm run gen:types`');
      process.exit(1);
    }
    console.log('generated.ts is up to date');
  } else {
    writeFileSync(out, text);
    console.log(`wrote ${out}`);
  }
}
