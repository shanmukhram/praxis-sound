//! The labelled-set accuracy test (WP-D2, PRD success criterion and the Phase 5 exit): tempo
//! within 2 BPM and the right key on at least 90% of the music clips, and classification
//! accuracy (music / sfx / ambience, target 90%).
//!
//! The clips are scores in `crates/praxis-analyze/tests/clips/` (see `clipgen`), rendered here by
//! the real engine (this crate has the engine; praxis-analyze does not) and measured with
//! `praxis_analyze::sound_profile`, exactly as `praxis analyze` measures a dropped clip. Clips
//! that need the Upright Piano KW pack are skipped when it is not installed.
//!
//! `cargo test -p praxis-cli --release --test labelled_set -- --nocapture` prints every clip.

mod clipgen;

use clipgen::{Label, apply_post, clips_dir, read_labels, score_for, specs};
use praxis_analyze::profile::ClipKind;
use praxis_analyze::{ProfileOptions, sound_profile};
use praxis_engine::{RenderOptions, render_offline};
use praxis_instruments::Registry;
use praxis_score::{Key, Score};

/// Regenerates the committed scores and labels.json from `clipgen::specs`.
#[test]
#[ignore = "writes crates/praxis-analyze/tests/clips; run by hand after changing clipgen"]
fn write_clip_scores() {
    let dir = clips_dir();
    std::fs::create_dir_all(&dir).unwrap();
    for e in std::fs::read_dir(&dir).unwrap().flatten() {
        if e.file_name().to_string_lossy().ends_with(".score.json") {
            std::fs::remove_file(e.path()).unwrap();
        }
    }
    let mut labels = Vec::new();
    for e in specs() {
        let v = score_for(&e);
        let score: Score = serde_json::from_value(v).expect("generated score parses");
        let report = praxis_score::validate::validate(&score);
        assert!(report.is_valid(), "{}: {:?}", e.id, report.errors);
        let label = clipgen::label_for(&e);
        std::fs::write(dir.join(&label.score), praxis_score::to_json(&score) + "\n").unwrap();
        labels.push(label);
    }
    let all = clipgen::Labels {
        version: 1,
        note: "Self-made labelled set (WP-D2): every clip is a score rendered by the engine at \
               `sample_rate`, then `post` is applied (gain_db, white noise at noise_db relative \
               to the render's RMS). Labels are what the score says. Generated by \
               crates/praxis-cli/tests/clipgen; no audio is stored."
            .into(),
        clips: labels,
    };
    std::fs::write(
        dir.join("labels.json"),
        serde_json::to_string_pretty(&all).unwrap() + "\n",
    )
    .unwrap();
}

fn key_name(k: &Key) -> String {
    k.display()
}

fn label_key(l: &Label) -> Option<Key> {
    l.key
        .as_ref()
        .and_then(|v| serde_json::from_value::<Key>(v.clone()).ok())
}

fn kind_name(k: ClipKind) -> &'static str {
    match k {
        ClipKind::Music => "music",
        ClipKind::Sfx => "sfx",
        ClipKind::Ambience => "ambience",
    }
}

#[test]
fn labelled_set_accuracy() {
    let labels = read_labels();
    let registry = Registry::with_default_packs();
    let (mut tempo_n, mut tempo_ok) = (0usize, 0usize);
    let (mut key_n, mut key_ok) = (0usize, 0usize);
    let (mut both_n, mut both_ok) = (0usize, 0usize);
    let (mut class_n, mut class_ok) = (0usize, 0usize);
    let mut skipped = Vec::new();
    let mut misses = Vec::new();
    let mut confusion = std::collections::BTreeMap::<(String, String), usize>::new();
    for (idx, l) in labels.clips.iter().enumerate() {
        if let Some(pack) = &l.needs_pack
            && !registry.packs().has_pack(pack)
        {
            skipped.push(l.id.clone());
            continue;
        }
        let text = std::fs::read_to_string(clips_dir().join(&l.score)).expect("score file");
        let score = praxis_score::from_json(&text).expect("score loads");
        let opts = RenderOptions {
            sample_rate: l.sample_rate,
            ..RenderOptions::default()
        };
        let mut audio = render_offline(&score, &registry, &opts)
            .unwrap_or_else(|e| panic!("{}: {e}", l.id))
            .master;
        apply_post(&mut audio, &l.post, idx as u64);
        let p = sound_profile(
            &audio.left,
            &audio.right,
            l.sample_rate,
            &ProfileOptions {
                file_name: format!("{}.wav", l.id),
                ..ProfileOptions::default()
            },
        )
        .expect("profile");
        let kind = kind_name(p.class.kind);
        class_n += 1;
        if kind == l.class {
            class_ok += 1;
        }
        *confusion
            .entry((l.class.clone(), kind.to_string()))
            .or_insert(0) += 1;
        let mut line = format!(
            "{:<40} {:<8} -> {:<8} ({:.2})",
            l.id, l.class, kind, p.class.confidence
        );
        let mut t_ok = true;
        if let Some(bpm) = l.tempo_bpm {
            tempo_n += 1;
            let got = p.tempo.as_ref().map(|t| (t.bpm, t.confidence));
            t_ok = got.is_some_and(|(b, _)| (b - bpm).abs() <= 2.0);
            tempo_ok += t_ok as usize;
            line += &format!(
                " | tempo {bpm:>5.1} -> {} {}",
                got.map_or("none".to_string(), |(b, c)| format!("{b:>6.2} ({c:.2})")),
                if t_ok { "ok" } else { "MISS" }
            );
        }
        if let Some(k) = label_key(l) {
            key_n += 1;
            let got = p.key.as_ref().map(|e| (e.key, e.confidence));
            let k_ok = got.is_some_and(|(g, _)| g.tonic == k.tonic && g.mode == k.mode);
            key_ok += k_ok as usize;
            both_n += 1;
            both_ok += (k_ok && t_ok) as usize;
            line += &format!(
                " | key {} -> {} {}",
                key_name(&k),
                got.map_or("none".to_string(), |(g, c)| format!(
                    "{} ({c:.2})",
                    key_name(&g)
                )),
                if k_ok { "ok" } else { "MISS" }
            );
            if !k_ok || !t_ok {
                misses.push(format!("{}: {}", l.id, l.description));
            }
        } else if !t_ok {
            misses.push(format!("{}: {}", l.id, l.description));
        }
        if kind != l.class {
            misses.push(format!(
                "{}: class {} read as {kind} (scores {:?}): {}",
                l.id, l.class, p.class.scores, l.description
            ));
        }
        eprintln!("{line}");
    }
    let pct = |a: usize, b: usize| 100.0 * a as f64 / b.max(1) as f64;
    eprintln!("---");
    eprintln!(
        "tempo within 2 BPM: {tempo_ok} of {tempo_n} ({:.1}%)",
        pct(tempo_ok, tempo_n)
    );
    eprintln!(
        "key correct: {key_ok} of {key_n} ({:.1}%)",
        pct(key_ok, key_n)
    );
    eprintln!(
        "tempo and key both right (keyed clips): {both_ok} of {both_n} ({:.1}%)",
        pct(both_ok, both_n)
    );
    eprintln!(
        "class correct: {class_ok} of {class_n} ({:.1}%)",
        pct(class_ok, class_n)
    );
    eprintln!("confusion (label -> read): {confusion:?}");
    eprintln!("skipped (pack missing): {skipped:?}");
    for m in &misses {
        eprintln!("miss: {m}");
    }
    assert!(tempo_n >= 30 && key_n >= 30, "too few clips rendered");
    assert!(
        pct(tempo_ok, tempo_n) >= 90.0,
        "tempo accuracy {:.1}%",
        pct(tempo_ok, tempo_n)
    );
    assert!(
        pct(key_ok, key_n) >= 90.0,
        "key accuracy {:.1}%",
        pct(key_ok, key_n)
    );
    assert!(
        pct(class_ok, class_n) >= 90.0,
        "class accuracy {:.1}%",
        pct(class_ok, class_n)
    );
}
